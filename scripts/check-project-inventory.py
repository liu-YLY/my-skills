"""Keep the maintained README inventory aligned with actual skill files."""

import argparse
import json
from pathlib import Path

FALLBACK_CHARS_PER_TOKEN = 1.55


def estimate_tokens(paths: list[Path]) -> int:
    characters = sum(len(path.read_text(encoding="utf-8")) for path in paths)
    return round(characters / FALLBACK_CHARS_PER_TOKEN)


def load_budgets(root: Path) -> dict:
    path = root / "scripts" / "context-budget.json"
    return json.loads(path.read_text(encoding="utf-8")).get("skills", {})


def primary_mode(name: str, budgets: dict) -> tuple[str | None, dict]:
    modes = budgets.get(name, {}).get("modes", {})
    for candidate in ("default", "route"):
        if candidate in modes:
            return candidate, modes[candidate]
    if modes:
        mode_name = sorted(modes)[0]
        return mode_name, modes[mode_name]
    return None, {}


def mode_paths(skill: Path, mode: dict) -> list[Path]:
    paths = [skill.parent / rel for rel in mode.get("files", [])]
    return [path for path in paths if path.is_file()]


def inventory(root: Path) -> str:
    budgets = load_budgets(root)
    rows = ["## 项目文件构成", "",
            "<!-- Generated by scripts/check-project-inventory.py --write -->", "",
            "以下统计由当前文件生成。Token 按字符数 / 1.55 估算，默认路径取 context-budget.json 中该 skill 的主模式，未配置的技能以 — 表示；实际上下文与 token 消耗以运行记录为准。", "",
            "| Skill | 入口行数 | 入口 Token(估) | 默认路径 Token(估) | 配套 Markdown 文件数 |",
            "|---|---:|---:|---:|---:|"]
    mode_notes = []
    skills = sorted(root.glob("plugins/*/skills/*/SKILL.md"))
    for skill in skills:
        name = skill.parent.name
        text = skill.read_text(encoding="utf-8")
        references = [p for p in skill.parent.rglob("*.md")
                      if p.name not in {"SKILL.md", "README.md", "CHANGELOG.md"}
                      and "docs" not in p.relative_to(skill.parent).parts
                      and ".venv-tools" not in p.parts]
        mode_name, mode = primary_mode(name, budgets)
        default_tokens = f"{estimate_tokens(mode_paths(skill, mode)):,}" if mode_name else "—"
        rows.append(f"| {name} | {len(text.splitlines())} | "
                    f"{round(len(text) / FALLBACK_CHARS_PER_TOKEN):,} | {default_tokens} | {len(references)} |")
        modes = budgets.get(name, {}).get("modes", {})
        extras = [f"{extra} ≈ {estimate_tokens(mode_paths(skill, modes[extra])):,}"
                  for extra in sorted(modes) if extra != mode_name]
        if extras:
            mode_notes.append(f"{name} 另有 " + "、".join(extras) + " token")
    if mode_notes:
        rows.extend(["", "默认路径按主模式估算；" + "；".join(mode_notes) + "。"])
    plugin_count = len({skill.parents[2] for skill in skills})
    testing_count = sum(skill.parents[2].name == "testing" for skill in skills)
    mcp_count = len(list(root.glob("plugins/testing/mcp-servers/*/pyproject.toml")))
    rows.extend(["", f"{plugin_count} 个插件共包含 {len(skills)} 个 Skills，测试插件包含 {testing_count} 个 Skills 和 {mcp_count} 个可选 MCP 服务。",
                 "模式需要的参考文件按需读取；模型耗时与 token 应以实际运行记录为准。", "", ""])
    return "\n".join(rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    path = root / "README.md"
    text = path.read_text()
    heading = "## 项目文件构成" if "## 项目文件构成" in text else "## Token 消耗分析"
    start, end = text.index(heading), text.index("## 快速开始")
    updated = text[:start] + inventory(root) + text[end:]
    if args.write:
        path.write_text(updated)
    elif updated != text:
        raise SystemExit("README inventory is stale; run scripts/check-project-inventory.py --write")
    else:
        print("Project inventory matches the current files.")


if __name__ == "__main__":
    main()
